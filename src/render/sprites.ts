export type SpriteName = keyof typeof SPRITES;
export type Sprite = HTMLCanvasElement;

/** Draws a sprite into a fresh canvas, optionally mirrored and with colours swapped. */
export function paint(name: SpriteName, opts: { flip?: boolean; recolor?: Record<string, string> } = {}): Sprite {
  const rows = SPRITES[name];
  const h = rows.length;
  const w = rows[0].length;
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const ctx = c.getContext('2d')!;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      let ch = rows[y][opts.flip ? w - 1 - x : x];
      if (ch === '.') continue;
      if (opts.recolor?.[ch]) ch = opts.recolor[ch];
      ctx.fillStyle = PIXELS[ch] ?? ch;
      ctx.fillRect(x, y, 1, 1);
    }
  }
  return c;
}

/** Every sprite, plus left-facing copies (suffix L) for the ones that face right. */
export class Atlas {
  private readonly cache = new Map<string, Sprite>();

  get(name: SpriteName, flip = false): Sprite {
    const key = flip ? `${name}:L` : name;
    let s = this.cache.get(key);
    if (!s) this.cache.set(key, (s = paint(name, { flip })));
    return s;
  }
}

/** A sprite as a crisp, scaled-up image URL for the DOM (cards, item slots). */
export function spriteUrl(name: SpriteName, scale: number, recolor?: Record<string, string>): string {
  const src = paint(name, { recolor });
  const c = document.createElement('canvas');
  c.width = src.width * scale;
  c.height = src.height * scale;
  const ctx = c.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(src, 0, 0, c.width, c.height);
  return c.toDataURL();
}
